  async function migrateEmployeeAssets(client) {
    await client.query(`
      CREATE TABLE IF NOT EXISTS employee_assets (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
        asset_category TEXT NOT NULL DEFAULT 'other',
        device_assigned TEXT,
        asset_id TEXT,
        mobile_number TEXT,
        access_card TEXT,
        issue_date TEXT,
        return_date TEXT,
        software_access TEXT,
        company_email TEXT,
        sort_order INTEGER NOT NULL DEFAULT 0,
        created_at TEXT NOT NULL DEFAULT to_char((now() AT TIME ZONE 'Asia/Kolkata'), 'YYYY-MM-DD HH24:MI:SS')
      )
    `);
    await client.query(
      `CREATE INDEX IF NOT EXISTS idx_employee_assets_user ON employee_assets(user_id)`
    );

    const { rows: countRows } = await client.query(
      `SELECT COUNT(*)::int AS c FROM employee_assets`
    );
    if (Number(countRows[0]?.c || 0) === 0) {
      await client.query(`
        INSERT INTO employee_assets (
          user_id, asset_category, device_assigned, asset_id, mobile_number, access_card,
          issue_date, return_date, software_access, company_email, sort_order
        )
        SELECT user_id, 'laptop_desktop', laptop_desktop_assigned, asset_id, company_mobile,
               access_card, equipment_issue_date, equipment_return_date,
               software_access_provisioning, company_email_account, 0
        FROM employee_profiles
        WHERE COALESCE(laptop_desktop_assigned, asset_id, company_mobile, access_card,
                       equipment_issue_date, equipment_return_date,
                       software_access_provisioning, company_email_account) IS NOT NULL
      `);
    }
  }

  async function migrateCompensationLeave(client) {
    await client.query(
      `ALTER TABLE leave_balances ADD COLUMN IF NOT EXISTS compensation DOUBLE PRECISION NOT NULL DEFAULT 0`
    );

    // Refresh leave_type checks to allow compensation leave.
    await client.query(`
      DO $$
      DECLARE
        con_name text;
      BEGIN
        FOR con_name IN
          SELECT c.conname
          FROM pg_constraint c
          JOIN pg_class t ON t.oid = c.conrelid
          WHERE t.relname = 'leave_requests'
            AND c.contype = 'c'
            AND pg_get_constraintdef(c.oid) ILIKE '%leave_type%'
        LOOP
          EXECUTE format('ALTER TABLE leave_requests DROP CONSTRAINT IF EXISTS %I', con_name);
        END LOOP;
        ALTER TABLE leave_requests
          ADD CONSTRAINT leave_requests_leave_type_check
          CHECK (leave_type IN ('casual', 'earned', 'sick', 'compensation', 'wfh', 'restricted'));
      EXCEPTION
        WHEN duplicate_object THEN NULL;
      END $$;
    `);

    await client.query(`
      DO $$
      DECLARE
        con_name text;
      BEGIN
        FOR con_name IN
          SELECT c.conname
          FROM pg_constraint c
          JOIN pg_class t ON t.oid = c.conrelid
          WHERE t.relname = 'balance_credits'
            AND c.contype = 'c'
            AND pg_get_constraintdef(c.oid) ILIKE '%leave_type%'
        LOOP
          EXECUTE format('ALTER TABLE balance_credits DROP CONSTRAINT IF EXISTS %I', con_name);
        END LOOP;
        ALTER TABLE balance_credits
          ADD CONSTRAINT balance_credits_leave_type_check
          CHECK (leave_type IN ('casual', 'earned', 'sick', 'compensation'));
      EXCEPTION
        WHEN duplicate_object THEN NULL;
        WHEN undefined_table THEN NULL;
      END $$;
    `);
  }

