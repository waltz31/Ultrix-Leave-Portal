import './time.js';
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import pg from 'pg';
import { isPostgres, translateSql, toPgPlaceholders } from './sqlDialect.js';

const __dirname = path.dirname(fileURLToPath(import.meta.url));

function wrapSqlite(raw) {
  return {
    dialect: 'sqlite',
    ready: Promise.resolve(),
    prepare(sql) {
      const stmt = raw.prepare(sql);
      return {
        get: async (...params) => stmt.get(...params),
        all: async (...params) => stmt.all(...params),
        run: async (...params) => stmt.run(...params),
      };
    },
    exec: async (sql) => {
      raw.exec(sql);
    },
    async transaction(fn) {
      return fn();
    },
  };
}

function createPostgres() {
  const pool = new pg.Pool({
    connectionString: process.env.DATABASE_URL,
    ssl:
      process.env.DATABASE_SSL === 'false'
        ? false
        : { rejectUnauthorized: false },
    max: 10,
    connectionTimeoutMillis: 15000,
    idleTimeoutMillis: 30000,
  });

  function clientQuery(client, sql, params) {
    const translated = toPgPlaceholders(translateSql(sql));
    return client.query(translated, params);
  }

  function makePrepare(queryFn) {
    return (sql) => ({
      get: async (...params) => {
        const { rows } = await queryFn(sql, params);
        return rows[0];
      },
      all: async (...params) => {
        const { rows } = await queryFn(sql, params);
        return rows;
      },
      run: async (...params) => {
        let text = sql;
        if (/^\s*INSERT\s+/i.test(text) && !/RETURNING\b/i.test(text)) {
          text = `${text.replace(/;?\s*$/, '')} RETURNING id`;
        }
        const result = await queryFn(text, params);
        return {
          lastInsertRowid: result.rows[0]?.id ?? 0,
          changes: result.rowCount ?? 0,
        };
      },
    });
  }

  let readyResolve;
  let readyReject;
  const ready = new Promise((resolve, reject) => {
    readyResolve = resolve;
    readyReject = reject;
  });

  const adapter = {
    dialect: 'postgres',
    ready,
    prepare: makePrepare((sql, params) => clientQuery(pool, sql, params)),
    exec: async (sql) => {
      await pool.query(translateSql(sql));
    },
    async transaction(fn) {
      const client = await pool.connect();
      const prevPrepare = adapter.prepare;
      try {
        await client.query('BEGIN');
        adapter.prepare = makePrepare((sql, params) => clientQuery(client, sql, params));
        const result = await fn();
        await client.query('COMMIT');
        return result;
      } catch (err) {
        try {
          await client.query('ROLLBACK');
        } catch {
          // ignore
        }
        throw err;
      } finally {
        adapter.prepare = prevPrepare;
        client.release();
      }
    },
  };

  async function migrateInvoices(client) {
    await client.query(`
      CREATE TABLE IF NOT EXISTS invoices (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
        invoice_number TEXT NOT NULL,
        invoice_date TEXT NOT NULL,
        billing_period TEXT NOT NULL,
        consultant TEXT NOT NULL,
        total_amount DOUBLE PRECISION NOT NULL DEFAULT 0,
        data_json TEXT NOT NULL,
        pdf_data TEXT,
        created_at TEXT NOT NULL DEFAULT to_char((now() AT TIME ZONE 'Asia/Kolkata'), 'YYYY-MM-DD HH24:MI:SS')
      )
    `);
    await client.query(
      `ALTER TABLE invoices ADD COLUMN IF NOT EXISTS submitter_deleted_at TEXT`
    );
    await client.query(`
      DELETE FROM invoices a
      USING invoices b
      WHERE a.id < b.id
        AND a.user_id = b.user_id
        AND a.invoice_number = b.invoice_number
        AND a.submitter_deleted_at IS NULL
        AND b.submitter_deleted_at IS NULL
    `);
    await client.query(`DROP INDEX IF EXISTS idx_invoices_user_number`);
    await client.query(`
      CREATE UNIQUE INDEX IF NOT EXISTS idx_invoices_user_number
        ON invoices(user_id, invoice_number)
        WHERE submitter_deleted_at IS NULL
    `);
    await client.query(`
      CREATE INDEX IF NOT EXISTS idx_invoices_billing_period ON invoices(billing_period)
    `);
    await client.query(`
      CREATE INDEX IF NOT EXISTS idx_invoices_user ON invoices(user_id)
    `);
  }

  async function runBootstrapSchema(client) {
    const schemaPath = path.join(__dirname, 'schema.pg.sql');
    const schema = fs.readFileSync(schemaPath, 'utf8');
    const statements = schema
      .split(';')
      .map((s) => s.trim())
      .filter((s) => s && !s.startsWith('--'))
      .filter((s) => !/\bidx_invoices_user_number\b/i.test(s));
    for (const statement of statements) {
      await client.query(statement);
    }
  }

  async function initSchema() {
    const client = await pool.connect();
    try {
      await client.query('SELECT 1');
      const { rows } = await client.query(`SELECT to_regclass('public.users') AS users`);
      if (!rows[0]?.users) {
        console.log('Bootstrapping Postgres schema…');
        await runBootstrapSchema(client);
      }
      await migrateInvoices(client);
      console.log('Connected to Supabase/Postgres');
      readyResolve();
    } catch (err) {
      console.error('Database initialization failed:', err);
      readyReject(err);
    } finally {
      client.release();
    }
  }

  initSchema();
  return adapter;
}

let db;
if (isPostgres) {
  db = createPostgres();
} else if (process.env.NODE_ENV === 'production') {
  throw new Error(
    'DATABASE_URL is not set. On Render, add your Supabase Postgres URI as DATABASE_URL. SQLite is only for local development.'
  );
} else {
  const { default: sqlite } = await import('./sqliteInit.js');
  db = wrapSqlite(sqlite);
}

export default db;
